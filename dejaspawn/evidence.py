NOTES = {
    "REAL": "Mode REAL: at least one platform was restored against a live target.",
    "MOCK": "Mode MOCK: restores went into a mock (sandbox), not a live account.",
    "DRY-RUN": "Mode DRY-RUN: nothing was sent to a live target (sandbox).",
    "FIXTURE": "Mode FIXTURE: synthetic data only.",
}


def _load(p):
    return json.load(open(p, encoding="utf-8"))


def _pick_drill(run):
    ds = sorted(glob.glob("receipts/*-drill.json"))
    if not ds:
        raise SystemExit(
            "no drill receipt under receipts/; run: python -m dejaspawn drill --card"
        )
    if not run:
        return ds[-1]
    for p in reversed(ds):
        for pl in _load(p)["platforms"].values():
            if any(run in f.get("path", "") for f in pl.get("files", [])):
                return p
    raise SystemExit(f"no drill receipt for run id {run}")


def _mirrors(drill):
    out = []
    for name, pl in drill["platforms"].items():
        if pl.get("mode") in ("NO-MIRROR", "MOCK-UNAVAILABLE"):
            continue
        c = [
            p
            for p in sorted(glob.glob(f"receipts/*-mirror-{name}.json"))
            if _load(p)["ended"] <= drill["ended"]
        ]
        if c:
            out.append(c[-1])
    return out


def build(run=None, out_root="evidence"):
    key = load_key()
    lp = _pick_drill(run)
    drill = _load(lp)
    ep = lp + ".dsse.json"
    if not os.path.isfile(ep):
        raise SystemExit("drill has no DSSE attestation: " + ep)
    mode = run_mode(drill["platforms"])
    date = time.strftime("%Y-%m-%d", time.gmtime())
    d = os.path.join(out_root, date)
    if os.path.exists(d):
        shutil.rmtree(d)
    os.makedirs(os.path.join(d, "attestations"))
    md, txt = card.render(drill, ep)
    files = {"respawn_card.md": md.encode(), "respawn_card.txt": txt.encode()}
    att = [lp, ep]
    for m in _mirrors(drill):
        att += [m, m + ".dsse.json"]
    for p in att:
        if os.path.isfile(p):
            files["attestations/" + os.path.basename(p)] = open(p, "rb").read()
    files["attest_verify.py"] = open(
        os.path.join(HERE, "attest_verify.py"), "rb"
    ).read()
    files["pubkey.hex"] = (pub_raw(key).hex() + "\n").encode()
    files["keyid.txt"] = (keyid_of(key) + "\n").encode()
    files["verify.sh"] = VERIFY_SH.encode()
    files["verify.cmd"] = VERIFY_CMD.replace("\n", "\r\n").encode()
    files["CONTROL_MAP.md"] = CONTROL_MAP.format(fetch=FETCH_DATE, mode=mode).encode()
    files["README.md"] = README.format(
        date=date,
        run=os.path.basename(lp)[:-5],
        mode=mode,
        modenote=NOTES[mode],
        ver=__version__,
        now=_utc(time.time()),
        keyid=keyid_of(key),
    ).encode()
    for n, b in files.items():
        os.makedirs(os.path.dirname(os.path.join(d, n)), exist_ok=True)
        with open(os.path.join(d, n), "wb") as f:
            f.write(b)
    listing = [
        {"path": n, "sha256": hashlib.sha256(b).hexdigest(), "bytes": len(b)}
        for n, b in sorted(files.items())
    ]
    mp = os.path.join(d, "MANIFEST.json")
    with open(mp, "w", encoding="utf-8") as f:
        json.dump({"version": "dejaspawn-evidence-1", "files": listing}, f, indent=2)
        f.write("\n")
    now = time.time()
    stmt = {
        "_type": "https://in-toto.io/Statement/v1",
        "subject": [
            {"name": x["path"], "digest": {"sha256": x["sha256"]}} for x in listing
        ]
        + [{"name": "MANIFEST.json", "digest": {"sha256": sha256_file(mp)}}],
        "predicateType": PREDICATE_TYPE,
        "predicate": {
            "producer": {"tool": "dejaspawn", "version": __version__},
            "started": _utc(now),
            "ended": _utc(now),
            "environment": {"host_os": platform.system().lower(), "run_mode": mode},
            "drill": os.path.basename(lp),
        },
    }
    with open(mp + ".dsse.json", "w", encoding="utf-8") as f:
        json.dump(make_envelope(stmt, key), f, indent=2)
        f.write("\n")
    try:
        os.chmod(os.path.join(d, "verify.sh"), 0o755)
    except OSError:
        pass
    return d
